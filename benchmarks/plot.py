"""Generate benchmarks/RESULTS.md and charts from stored benchmark results (benchmarks/results/*.json).

    uv run --with matplotlib python benchmarks/plot.py

Only reads stored real runs; it never runs anything itself.
"""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from bumpless import fsutil  # noqa: E402
from bumpless.bench import all_results  # noqa: E402

OUT = Path("benchmarks")
CHARTS = OUT / "charts"


def fmt(v, suffix="", digits=None):
    if v is None:
        return "—"
    return f"{round(v, digits) if digits is not None else v}{suffix}"


def pct(rate) -> str:
    return "—" if rate is None else f"{round(rate * 100)}%"


def status(x: dict) -> str:
    err = (x.get("error") or "").split(":")[0]
    return x["status"] + (f" ({err})" if err else "") + (" \\*" if x.get("status_note") else "")


def table(r: dict) -> str:
    lines = ["| Repo | Kind | Upgrade | Status | Tests fixed | Behavior kept | Coverage | Cost | Time | Recipe | Run |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for x in r["runs"]:
        lines.append(
            f"| {x['name']} | {x['kind']} | {x['package']} {x['old_version']} → {x['new_version']} | {status(x)} | "
            f"{x['tests_fixed']}/{x['tests_failing_before_fix']} | {pct(x['characterization_pass_rate'])} | "
            f"{fmt(x['coverage_percent'], '%')} | ${x['cost_usd']:.4f} | {round(x['duration_s'])}s | "
            f"{'reused' if x['recipe_reused'] else 'first run'} | `{x['run_id']}` |")
    lines += [f"\n\\* `{x['run_id']}`: {x['status_note']}" for x in r["runs"] if x.get("status_note")]
    return "\n".join(lines)


def provider(r: dict) -> str:
    # Results from before this field existed were all run on Token Factory.
    host = r.get("provider") or "api.tokenfactory.nebius.com"
    return "Token Factory" if host == "api.tokenfactory.nebius.com" else f"{host} (cost = Token Factory list price, not billed)"


def summary(r: dict) -> str:
    s = r["summary"]
    infra = f"; {s['infra_errors']} stopped by an account/budget error, not counted" if s.get("infra_errors") else ""
    return (f"- **{s['green']}/{s['repos']} green** ({s['partial']} partial, {s['failed']} failed{infra})\n"
            f"- Tests fixed: {s['tests_fixed']}/{s['tests_failing_before_fix']}\n"
            f"- Median verified change coverage: {fmt(s['median_coverage_percent'], '%')}\n"
            f"- Median characterization pass rate: {pct(s['median_characterization_pass_rate'])}\n"
            f"- Median time: {fmt(s['median_duration_s'], 's', 0)} · median cost: ${s['median_cost_usd']} · "
            f"total cost: ${s['total_cost_usd']} · escalations: {s['escalations']}")


def charts(latest: dict) -> list[str]:
    modes = [m for m in ("tiered", "all-ultra") if m in latest]
    if len(modes) < 2:
        return []
    CHARTS.mkdir(parents=True, exist_ok=True)
    made = []
    for key, label, fn, val in (
        ("success", "Success rate (% green)", "success.png", lambda s: 100 * (s["success_rate"] or 0)),
        ("cost", "Total cost (USD)", "cost.png", lambda s: s["total_cost_usd"]),
    ):
        fig, ax = plt.subplots(figsize=(5, 2.2))
        ax.barh(modes, [val(latest[m]["summary"]) for m in modes], color="#34d399")
        ax.set_xlabel(label)
        for i, m in enumerate(modes):
            v = val(latest[m]["summary"])
            ax.text(v, i, f" {v:.0f}%" if key == "success" else f" ${v:.3f}", va="center")
        fig.tight_layout()
        fig.savefig(CHARTS / fn, dpi=150)
        plt.close(fig)
        made.append(f"![{label}](charts/{fn})")
    return made


def main() -> None:
    results = all_results()
    latest: dict[str, dict] = {}
    for r in results:
        latest.setdefault(r["routing"], r)
    parts = ["# Benchmark results", "",
             "Generated by `benchmarks/plot.py` from `benchmarks/results/*.json`. Every number comes from a stored real",
             "run; run IDs link to the full event log in the web app (`/runs/<id>`).", ""]
    if not results:
        parts.append("No benchmark results yet.")
    imgs = charts(latest)
    if imgs:
        t, u = latest["tiered"]["summary"], latest["all-ultra"]["summary"]
        saving = 1 - t["total_cost_usd"] / u["total_cost_usd"] if u["total_cost_usd"] else None
        parts += ["## Tiered vs all-Ultra routing", "", *imgs, ""]
        if saving is not None:
            parts += [f"Tiered routing cost **{saving:.0%} less** than all-Ultra (${t['total_cost_usd']:.3f} vs "
                      f"${u['total_cost_usd']:.3f}) with {t['green']}/{t['repos']} vs {u['green']}/{u['repos']} green.", ""]
        tc, uc = latest["tiered"].get("commit"), latest["all-ultra"].get("commit")
        if tc != uc:
            parts += [f"**Not like-for-like:** these two runs used different code (tiered `{tc}`, all-Ultra `{uc}`).", ""]
        for m in ("tiered", "all-ultra"):
            if latest[m].get("models"):
                models = ", ".join(f"{k} `{v}`" for k, v in latest[m]["models"].items())
                parts += [f"{m}: {provider(latest[m])}; models {models}", ""]
        parts += ["Each mode was run once per code version, and results vary between runs of the same code (see "
                  "All benchmark runs), so treat single-run differences as indicative only.", ""]
    for mode, r in latest.items():
        parts += [f"## Routing: {mode} (`{r['bench_id']}`)", "", summary(r), "", table(r), ""]
        first = [x["cost_usd"] for x in r["runs"] if not x["recipe_reused"]]
        reused = [x["cost_usd"] for x in r["runs"] if x["recipe_reused"]]
        if first and reused:
            parts += [f"Recipe reuse: first runs averaged ${sum(first) / len(first):.4f}; runs reusing a recipe "
                      f"averaged ${sum(reused) / len(reused):.4f}.", ""]
    if results:  # every run, not just the latest: results vary between runs of the same code
        parts += ["## All benchmark runs", "",
                  "| Benchmark | Routing | Code | Provider | Green | Partial | Failed | Tests fixed | Total cost | Median time |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        for r in results:
            s = r["summary"]
            parts.append(f"| `{r['bench_id']}` | {r['routing']} | {r.get('commit') or 'not recorded'} | "
                         f"{provider(r)} | {s['green']} | "
                         f"{s['partial']} | {s['failed']} | {s['tests_fixed']}/{s['tests_failing_before_fix']} | "
                         f"${s['total_cost_usd']:.3f} | {fmt(s['median_duration_s'], 's', 0)} |")
        parts.append("")
    fsutil.write(OUT / "RESULTS.md", "\n".join(parts).rstrip() + "\n")
    print(f"wrote {OUT / 'RESULTS.md'} from {len(results)} result file(s)")


if __name__ == "__main__":
    main()
