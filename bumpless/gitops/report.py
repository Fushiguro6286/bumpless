"""PR body / report Markdown, generated from a run result."""

BADGE = {"High": "🟢 High", "Medium": "🟡 Medium", "Low": "🔴 Low"}
STATUS = {"green": "✅ Green", "partial": "🟡 Partial", "failed": "❌ Failed"}


def _tests(t: dict | None) -> str:
    return f"{t['passed']} passed, {t['failed']} failed" if t else "n/a"


def render(r: dict, file_url: str | None = None) -> str:
    """`file_url`, if given, is a prefix like https://github.com/o/r/blob/<branch>/ for file:line links."""
    def link(path: str, line: int) -> str:
        return f"[{path}:{line}]({file_url}{path}#L{line})" if file_url else f"`{path}:{line}`"

    rb = r.get("rulebook") or {}
    rules = {x["id"]: x for x in rb.get("rules", [])}
    cov = r.get("coverage") or {}
    ch = r.get("characterization") or {}
    t = r.get("tests", {})
    lines = [
        f"## Bumpless: {r['package']} {r['old_version']} → {r['new_version']}",
        "",
        f"**Status:** {STATUS.get(r['status'], r['status'])} · **Verified change coverage:** "
        + (f"**{cov['percent']}%** ({cov['executed_changed_lines']}/{cov['executable_changed_lines']} changed lines "
           "executed by tests)" if cov.get("percent") is not None else "not measured")
        + f" · **Cost:** ${r['cost']['total_usd']:.4f} · **Time:** {r['duration_s']:.0f}s",
        "",
        "### Tests",
        "| | Result |", "|---|---|",
        f"| Old version ({r['old_version']}) | {_tests(t.get('old'))} |",
        f"| New version, before fix (the Dependabot red) | {_tests(t.get('new_before'))} |",
        f"| After Bumpless | {_tests(t.get('after'))} |",
    ]
    if ch.get("observations"):
        char_after = [x for x in t.get("after", {}).get("failing", []) if x.startswith("tests._bumpless")]
        lines += ["", f"**Characterization:** {ch['observations']} behaviors recorded on the old version; "
                  f"{ch['new_before']['failed']} changed before the fix, {len(char_after)} changed after. "
                  "Generated in `tests/_bumpless/`."]
    if cov.get("hunks"):
        lines += ["", "### Changes", "| Location | Rule | Source | Verified | Confidence | Model |",
                  "|---|---|---|---|---|---|"]
        for h in cov["hunks"]:
            rule = rules.get(h["rule_id"] or "")
            title = f"{h['rule_id']}: {rule['title']}" if rule else (h["rule_id"] or "—")
            src = f"[source]({h['source_url']})" if h.get("source_url") else "—"
            model = (h["model_tier"] or "—") + (" ↑" if h["escalated"] else "") + (" (repair)" if h["repaired"] else "")
            lines.append(f"| {link(h['path'], h['start'])} | {title} | {src} | {'✓' if h['verified'] else '✗'} | "
                         f"{BADGE[h['confidence']]} | {model} |")
        low = [h for h in cov["hunks"] if h["confidence"] == "Low"]
        if low:
            lines += ["", "### 🔴 Low confidence (please review)"]
            lines += [f"- {link(h['path'], h['start'])}: {'; '.join(h['reasons'])}" for h in low]
    if r.get("escalations"):
        lines += ["", "### Escalations"]
        lines += [f"- `{e['path']}` → {e['tier']}" for e in r["escalations"]]
    tv = r.get("tavily", {})
    lines += ["", "### Research (Tavily)",
              f"{tv.get('calls', 0)} calls ({', '.join(f'{k}: {v}' for k, v in tv.get('by_kind', {}).items())}). "
              + ("Recipe reused; research skipped." if r.get("recipe_reused") else
                 f"Rulebook built from {rb.get('official_pages', 0)} official pages.")
              + f" {sum(x['verified'] for x in rules.values())}/{len(rules)} rules verified against their sources."]
    by = r["cost"]["by_tier"]
    lines += ["", "### Cost (Nemotron on Nebius Token Factory)", "| Nano | Super | Ultra | Total |", "|---|---|---|---|",
              f"| ${by['nano']:.4f} | ${by['super']:.4f} | ${by['ultra']:.4f} | **${r['cost']['total_usd']:.4f}** |"]
    if r.get("manual_review"):
        lines += ["", "### Needs human review"] + [f"- {m}" for m in r["manual_review"]]
    lines += ["", "### Talk to me",
              "Reply with `@bumpless <request>`, e.g. `@bumpless explain the change in app/models.py`, "
              "`@bumpless revert the change to app/utils.py`, `@bumpless use model_dump(mode=\"json\") here instead`.",
              "", "---", "_Generated by Bumpless — Nemotron on Nebius Token Factory + Tavily_"]
    return "\n".join(lines) + "\n"
