"""Step 3: characterization tests. Super writes a probe; we run it on the OLD version, record goldens and
generate tests/_bumpless/test_characterization.py that asserts the same observations after the migration."""

import json
import re
import shutil
from pathlib import Path

from bumpless import fsutil
from bumpless.llm import prompts
from bumpless.pipeline import baseline
from bumpless.pipeline.context import RunContext
from bumpless.pipeline.scan import imports_package, python_files

CHAR_DIR = "tests/_bumpless"
HARNESS = Path(__file__).with_name("probe_harness.py")
MAX_FILES_CHARS = 50_000
MIN_OBSERVATIONS = 3

PROBE_HEADER = '''# Generated by Bumpless: records current behavior. Do not edit by hand.
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from _harness import dump, observe  # noqa: E402,F401

'''
PROBE_FOOTER = '''

if __name__ == "__main__":
    probe()
    pathlib.Path(sys.argv[1]).write_text(dump(), encoding="utf-8")
'''
TEST_FILE = '''# Generated by Bumpless: behavior recorded on {package} {old_version} must not change.
import importlib.util
import json
import pathlib

import pytest

HERE = pathlib.Path(__file__).parent
GOLDEN = json.loads((HERE / "golden.json").read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def observed():
    spec = importlib.util.spec_from_file_location("_bumpless_probe", HERE / "_probe.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    mod.probe()
    return json.loads(mod.dump())


@pytest.mark.parametrize("name", sorted(GOLDEN))
def test_behavior_unchanged(observed, name):
    assert observed.get(name) == GOLDEN[name]
'''


def source_files(ctx: RunContext) -> str:
    """Non-test files that import the package, plus files importing those modules (one hop)."""
    ws = ctx.workspace
    files = [f for f in python_files(ws) if "test" not in f.relative_to(ws).as_posix().lower()]
    direct = [f for f in files if imports_package(_parse(f), ctx.package)]
    mods = {".".join(f.relative_to(ws).with_suffix("").parts) for f in direct}
    users = [f for f in files if f not in direct and any(m in f.read_text(encoding="utf-8", errors="replace")
                                                         for m in mods)]
    blob, used = [], 0
    for f in direct + users:
        text = f.read_text(encoding="utf-8", errors="replace")
        if used + len(text) > MAX_FILES_CHARS:
            break
        used += len(text)
        blob.append(f"{f.relative_to(ws).as_posix()}\n```python\n{text}\n```")
    return "\n\n".join(blob)


def _parse(f: Path):
    import ast
    try:
        return ast.parse(f.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError:
        return ast.parse("")


def extract_code(reply: str) -> str:
    m = re.findall(r"```(?:python)?\n(.*?)```", reply, re.S)
    return max(m, key=len) if m else reply


def stable(a: dict, b: dict) -> dict:
    """Drop observations that differ between two identical runs (nondeterministic)."""
    return {k: v for k, v in a.items() if b.get(k) == v}


async def _run_probe(ctx: RunContext, out: str):
    r = await ctx.executor.run(ctx.workspace, [f"python {CHAR_DIR}/_probe.py {out}"], timeout_s=300)
    path = ctx.workspace / out
    if r.exit_code != 0 or not path.exists():
        return None, r.output[-4000:]
    return json.loads(path.read_text(encoding="utf-8")), ""


async def characterize(ctx: RunContext) -> dict:
    d = ctx.workspace / CHAR_DIR
    d.mkdir(parents=True, exist_ok=True)
    shutil.copy(HARNESS, d / "_harness.py")
    pkg_old = f'uv pip install -q "{ctx.package}=={ctx.old_version}"'
    await baseline.install(ctx, [pkg_old])  # probes record behavior on the OLD version
    files, feedback, golden = source_files(ctx), "", None
    for _ in range(3):
        reply = await ctx.llm.chat("probe", [{"role": "user", "content": prompts.render(
            "probe", package=ctx.package, files=files, feedback=feedback,
            **{"from": ctx.from_major, "to": ctx.to_major})}], step="characterize", max_tokens=16000)
        fsutil.write(d / "_probe.py", PROBE_HEADER + extract_code(reply).strip() + PROBE_FOOTER)
        first, err = await _run_probe(ctx, ".bumpless/golden1.json")
        if first is not None:
            second, err = await _run_probe(ctx, ".bumpless/golden2.json")
        if first is not None and second is not None:
            golden = stable(first, second)
            if len(golden) >= MIN_OBSERVATIONS:
                break
            err = f"only {len(golden)} stable observations; add more"
        feedback = f"\nYour previous probe failed on the current (old) version:\n{err}\nFix it.\n"
    if not golden or len(golden) < MIN_OBSERVATIONS:
        shutil.rmtree(d, ignore_errors=True)
        ctx.manual_review.append("Characterization probe could not be generated; behavior is covered only by "
                                 "the repository's own tests")
        await baseline.install(ctx, [f'uv pip install -q "{ctx.package}{ctx.target}"'])
        return {"observations": 0}

    fsutil.write(d / "golden.json", json.dumps(golden, sort_keys=True, indent=1) + "\n")
    fsutil.write(d / "test_characterization.py", TEST_FILE.format(package=ctx.package, old_version=ctx.old_version))
    old = await baseline.run_tests(ctx, CHAR_DIR)
    ctx.progress("characterize", f"{len(golden)} behaviors recorded on {ctx.package} {ctx.old_version}; "
                 f"characterization tests on old version: {old.passed} passed, {old.failed} failed")
    if old.failed:
        raise RuntimeError("characterization tests do not pass on the old version")

    await baseline.install(ctx, [f'uv pip install -q "{ctx.package}{ctx.target}"'])
    red = await baseline.run_tests(ctx, CHAR_DIR)
    ctx.progress("characterize", f"On {ctx.package} {ctx.new_version} before fix: {red.passed} passed, "
                 f"{red.failed} failed")
    return {"observations": len(golden), "old": old.summary(), "new_before": red.summary()}
