"""Step 9: branch + commit, then a PR (if the token can push) or a .patch + rendered report."""

import shutil

import git

from bumpless.gitops import github, report
from bumpless.pipeline.context import RunContext
from bumpless.pipeline.intake import ACTOR
from bumpless.settings import ROOT, settings

RUNS_DIR = ROOT / "data" / "runs"


def commit(ctx: RunContext, result: dict) -> str:
    repo = git.Repo(ctx.workspace)
    branch = f"bumpless/{ctx.package}-{ctx.to_major}"
    repo.git.checkout("-B", branch)
    repo.git.add("-A")
    msg = (f"Migrate {ctx.package} {ctx.old_version} -> {ctx.new_version}\n\n"
           f"Status: {result['status']}. Generated by Bumpless (Nemotron on {settings.provider} + Tavily).")
    repo.index.commit(msg, author=ACTOR, committer=ACTOR)
    return branch


def output(ctx: RunContext, source: str, result: dict, open_pr: bool) -> dict:
    """Writes data/runs/<id>/{bumpless.patch,report.md}; opens a PR when possible. Returns output info."""
    out_dir = RUNS_DIR / ctx.run_id
    out_dir.mkdir(parents=True, exist_ok=True)
    branch = commit(ctx, result)
    repo = git.Repo(ctx.workspace)
    base = repo.git.rev_parse(f"{branch}~1")
    (out_dir / "bumpless.patch").write_bytes(repo.git.format_patch("--stdout", base).encode("utf-8") + b"\n")
    info = {"branch": branch, "patch": str(out_dir / "bumpless.patch"), "report": str(out_dir / "report.md"),
            "pr_url": None, "pr_skipped_reason": None}

    gh = github.parse_repo(source)
    file_url = f"https://github.com/{gh[0]}/{gh[1]}/blob/{branch}/" if gh else None
    body = report.render(result, file_url)
    (out_dir / "report.md").write_text(body, encoding="utf-8")
    shutil.copy(out_dir / "report.md", ctx.workspace / ".bumpless" / "report.md")

    if not open_pr:
        info["pr_skipped_reason"] = "PR not requested (use --open-pr)"
    elif not gh:
        info["pr_skipped_reason"] = "source is not a GitHub repository"
    elif not settings.github_token or not github.can_push(settings.github_token, *gh):
        info["pr_skipped_reason"] = "GITHUB_TOKEN missing or has no push rights; download the patch instead"
    else:
        owner, name = gh
        remote = f"https://x-access-token:{settings.github_token}@github.com/{owner}/{name}.git"
        try:
            repo.git.push(remote, f"{branch}:{branch}", "--force")
        except git.GitCommandError as e:  # never leak the token in error messages
            raise RuntimeError(str(e).replace(settings.github_token, "***")) from None
        default = github.repo_info(settings.github_token, owner, name)["default_branch"]
        pr = github.open_pr(settings.github_token, owner, name, branch, default,
                            f"Bumpless: migrate {ctx.package} to {ctx.new_version}", body)
        info["pr_url"] = pr["html_url"]
    return info
